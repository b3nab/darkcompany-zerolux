import {
  cp,
  mkdir,
  mkdtemp,
  readdir,
  rename,
  rm,
  writeFile,
} from "node:fs/promises";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { atlas } from "./atlas";

const root = resolve(import.meta.dir, "..");
const history = join(root, "crates/zerolux/migrations");
const dialects = ["sqlite", "postgres"] as const;

async function files(directory: string) {
  const names = (await readdir(directory))
    .filter((name) => name.endsWith(".sql"))
    .sort();
  if (names.some((name) => !/^\d{4}_[a-z][a-z0-9_]*\.sql$/.test(name))) {
    throw new Error("Migration names must be NNNN_name.sql");
  }
  return names;
}

async function fingerprint(paths: string[]) {
  const hash = new Bun.CryptoHasher("sha256");
  for (const path of [...paths].sort()) {
    hash.update(path).update("\0");
    hash.update(await Bun.file(path).arrayBuffer());
  }
  return hash.digest("hex");
}

async function register() {
  const sqlite = await files(join(history, "sqlite"));
  const postgres = await files(join(history, "postgres"));
  if (JSON.stringify(sqlite) !== JSON.stringify(postgres)) {
    throw new Error("Both dialects must have the same migration versions");
  }
  const entries = sqlite.map((file) => {
    const name = `m${file.slice(0, -4)}`;
    return `    SqlMigration { name: "${name}", sqlite: include_str!("sqlite/${file}"), postgres: include_str!("postgres/${file}") },`;
  });
  const text = [
    "// Generated by scripts/generate-migration.ts. Do not edit.",
    "const MIGRATIONS: &[SqlMigration] = &[",
    ...entries,
    "];",
    "",
  ].join("\n");
  const destination = join(history, "registry.rs");
  const temporary = `${destination}.${process.pid}.tmp`;
  await writeFile(temporary, text, { flag: "wx" });
  await rename(temporary, destination);
}

async function command(
  argv: string[],
  options: { env?: Record<string, string | undefined>; output?: string } = {},
) {
  const child = Bun.spawn(argv, {
    cwd: root,
    env: options.env ?? process.env,
    stdin: "ignore",
    stdout: options.output ? Bun.file(options.output) : "inherit",
    stderr: "inherit",
  });
  const stop = () => child.kill("SIGTERM");
  process.once("SIGINT", stop);
  process.once("SIGTERM", stop);
  try {
    const code = await child.exited;
    if (code !== 0) throw new Error(`${argv[0]} exited with ${code}`);
  } finally {
    process.off("SIGINT", stop);
    process.off("SIGTERM", stop);
  }
}

async function generate(name: string) {
  if (!/^[a-z][a-z0-9_]{0,59}$/.test(name))
    throw new Error("Choose a lowercase migration name");
  const lock = join(root, ".zerolux/migration-generation.lock");
  await mkdir(join(root, ".zerolux"), { recursive: true });
  await mkdir(lock); // Never take over another generation, including an interrupted one.
  const directory = await mkdtemp(join(tmpdir(), "zerolux-migration-"));
  try {
    const binary = await atlas();
    const before = await files(join(history, "sqlite"));
    const pg = await files(join(history, "postgres"));
    if (JSON.stringify(before) !== JSON.stringify(pg))
      throw new Error("Migration histories differ");
    const inputs = [
      "Cargo.toml",
      "Cargo.lock",
      "crates/zerolux/Cargo.toml",
      "crates/zerolux/examples/schema-export.rs",
    ].map((path) => join(root, path));
    for await (const path of new Bun.Glob("crates/zerolux/src/**/*.rs").scan({
      cwd: root,
      absolute: true,
    }))
      inputs.push(path);
    const artifacts = dialects.flatMap((dialect) =>
      [...before, "atlas.sum"].map((file) => join(history, dialect, file)),
    );
    artifacts.push(join(history, "registry.rs"));
    const sourceBefore = await fingerprint(inputs);
    const historyBefore = await fingerprint(artifacts);
    const next =
      Math.max(0, ...before.map((file) => Number(file.slice(0, 4)))) + 1;
    if (next > 9999) throw new Error("Migration sequence exhausted");
    const basename = `${String(next).padStart(4, "0")}_${name}.sql`;
    const staged = join(directory, "migrations");
    await cp(history, staged, { recursive: true });
    const home = join(directory, "home");
    await mkdir(home);
    const env: Record<string, string | undefined> = {
      ...process.env,
      HOME: home,
      ATLAS_NO_UPDATE_NOTIFIER: "1",
    };
    delete env.DATABASE_URL;
    for (const key of Object.keys(env)) {
      if (key.startsWith("ATLAS_") && key !== "ATLAS_NO_UPDATE_NOTIFIER")
        delete env[key];
    }
    let engine = process.env.DOCKER_HOST;
    if (!engine) {
      const context = Bun.spawn(
        [
          "docker",
          "context",
          "inspect",
          "--format",
          "{{.Endpoints.docker.Host}}",
        ],
        {
          stdout: "pipe",
          stderr: "inherit",
        },
      );
      engine = (await new Response(context.stdout).text()).trim();
      if ((await context.exited) !== 0)
        throw new Error("Cannot resolve the local Docker engine");
    }
    if (!engine.startsWith("unix://") && !engine.startsWith("npipe://")) {
      throw new Error(
        "Generation requires a local Docker engine, not a remote host",
      );
    }
    env.DOCKER_HOST = engine;
    delete env.DOCKER_CONTEXT;
    // Both dialects come from one compiled invocation, never different source snapshots.
    const exported = join(directory, "schemas.json");
    await command(
      [
        "cargo",
        "run",
        "--locked",
        "-p",
        "zerolux",
        "--example",
        "schema-export",
        "--",
        "both",
      ],
      { output: exported },
    );
    const schemas: Record<string, unknown> = await Bun.file(exported).json();
    let changed = false;
    for (const dialect of dialects) {
      const schema = join(directory, `${dialect}.sql`);
      const sql = schemas[dialect];
      if (typeof sql !== "string")
        throw new Error(`No exported schema for ${dialect}`);
      await writeFile(schema, sql);
      const destination = join(staged, dialect);
      // Atlas creates and destroys its own PostgreSQL dev container. No workspace URL,
      // DATABASE_URL fallback, existing volume or shared test database is accepted.
      const dev =
        dialect === "sqlite"
          ? "sqlite://dev?mode=memory"
          : "docker://postgres/18/dev?search_path=public";
      await command(
        [
          binary,
          "migrate",
          "diff",
          name,
          "--dir",
          `file://${destination}`,
          "--to",
          `file://${schema}`,
          "--dev-url",
          dev,
        ],
        { env },
      );
      const created = (await readdir(destination)).filter(
        (file) => file.endsWith(".sql") && !before.includes(file),
      );
      if (created.length > 1)
        throw new Error("Atlas produced an unexpected set of migrations");
      if (created.length) {
        const sql = await Bun.file(join(destination, created[0]!)).text();
        if (/atlas:txmode\s+none\b/.test(sql)) {
          throw new Error(
            "This migration cannot run in the kernel's atomic transaction; no artifacts published",
          );
        }
        changed = true;
        await rename(
          join(destination, created[0]!),
          join(destination, basename),
        );
      } else {
        await writeFile(join(destination, basename), "", { flag: "wx" });
      }
      await command(
        [binary, "migrate", "hash", "--dir", `file://${destination}`],
        { env },
      );
    }
    if (
      (await fingerprint(inputs)) !== sourceBefore ||
      (await fingerprint(artifacts)) !== historyBefore
    ) {
      throw new Error(
        "Source or migration history changed during generation; nothing published",
      );
    }
    // Publish both artifacts before the registry can expose their version to the kernel.
    for (const dialect of dialects) {
      if (
        JSON.stringify(await files(join(history, dialect))) !==
        JSON.stringify(before)
      ) {
        throw new Error(
          "Migration history changed during generation; nothing published",
        );
      }
    }
    if (!changed) {
      console.log("The entities and versioned migrations already agree.");
      return;
    }
    for (const dialect of dialects) {
      await writeFile(
        join(history, dialect, basename),
        await Bun.file(join(staged, dialect, basename)).text(),
        { flag: "wx" },
      );
      await writeFile(
        join(history, dialect, "atlas.sum"),
        await Bun.file(join(staged, dialect, "atlas.sum")).text(),
      );
    }
    await register();
    console.log(
      `Generated ${basename} for SQLite and PostgreSQL. Review the artifacts before committing.`,
    );
  } finally {
    await rm(directory, { recursive: true, force: true });
    await rm(lock, { recursive: true });
  }
}

if (import.meta.main) {
  const [name, ...extra] = process.argv.slice(2);
  if (!name || extra.length)
    throw new Error(
      "Usage: bun scripts/generate-migration.ts <name|--register>",
    );
  if (name === "--register") await register();
  else await generate(name);
}
